<template>
  <div v-bind="rootAttrs" :class="rootClass" :style="rootStyle">
    <picture v-if="src && !isFailed" :class="LAYER_CLASS">
      <source v-if="webpSrc" :srcset="webpSrc" type="image/webp" />
      <img
        ref="img"
        :class="[LAYER_CLASS, cover ? 'object-cover' : 'object-contain']"
        :src="src"
        :alt="alt"
        :loading="eager ? 'eager' : 'lazy'"
        :style="{ objectPosition: position }"
        @load="handleLoad"
        @error="handleError"
      />
    </picture>
    <div v-if="gradient" :class="[LAYER_CLASS, 'hk-img__gradient', 'bg-no-repeat']" :style="{ backgroundImage: `linear-gradient(${gradient})` }" />
    <div v-if="$slots.placeholder && !isLoaded && !isFailed" :class="LAYER_CLASS">
      <slot name="placeholder" />
    </div>
    <div v-if="$slots.error && isFailed" :class="LAYER_CLASS">
      <slot name="error" />
    </div>
    <div class="hk-img__content relative flex-1 max-w-full">
      <slot />
    </div>
  </div>
</template>

<script setup lang="ts">
import { computed, onMounted, ref, useAttrs, useTemplateRef, watch } from 'vue'

import type { CssSize } from '@/types/css'
import { cn, toCssSize } from '@/utils/css'
import { getWebpSrc, readWebpEnvironment } from '@/utils/image'

// Props, slots and events follow Vuetify's v-img so a call site can swap one for the other.
interface Props {
  src: string
  alt?: string
  cover?: boolean
  eager?: boolean
  aspectRatio?: CssSize
  width?: CssSize
  height?: CssSize
  maxWidth?: CssSize
  maxHeight?: CssSize
  minWidth?: CssSize
  minHeight?: CssSize
  /** object-position of the image */
  position?: string
  /** The inside of a linear-gradient(), for example `to bottom, rgba(0,0,0,0), rgba(0,0,0,0.4)` */
  gradient?: string
}

interface Emits {
  (event: 'load', src: string): void
  (event: 'error', src: string): void
}

defineOptions({ inheritAttrs: false })

const props = defineProps<Props>()
const emit = defineEmits<Emits>()

const attrs = useAttrs()
const imgRef = useTemplateRef<HTMLImageElement>('img')

// Utility classes are generated by the app's UnoCSS, which finds them through the banner comment in dist.
// Image, gradient, placeholder and error all stack on one spot; the root is sized by aspect-ratio.
const ROOT_CLASS = 'hk-img relative flex grow shrink-0 max-w-full max-h-full overflow-hidden'
const LAYER_CLASS = 'absolute inset-0 w-full h-full'

// twMerge lets a downstream class override a default one (`overflow-visible` replaces `overflow-hidden`)
const rootClass = computed(() => cn(ROOT_CLASS, attrs.class))
const rootAttrs = computed(() => {
  const { class: _class, ...rest } = attrs

  return rest
})

const isLoaded = ref(false)
const isFailed = ref(false)
const naturalAspectRatio = ref<number>()

// <picture> only negotiates browser support, it doesn't check that the webp file exists, and a
// 404 on the selected <source> does not fall back to the <img>. The app's build guarantees the
// file, so there is deliberately no runtime fallback here.
const webpSrc = computed(() => getWebpSrc(props.src, readWebpEnvironment()))

const rootStyle = computed(() => {
  const aspectRatio = props.aspectRatio ?? naturalAspectRatio.value

  return {
    width: toCssSize(props.width),
    height: toCssSize(props.height),
    maxWidth: toCssSize(props.maxWidth),
    maxHeight: toCssSize(props.maxHeight),
    minWidth: toCssSize(props.minWidth),
    minHeight: toCssSize(props.minHeight),
    aspectRatio: aspectRatio === undefined ? undefined : `${aspectRatio}`,
  }
})

function handleLoad() {
  const { naturalWidth = 0, naturalHeight = 0 } = imgRef.value ?? {}

  if (naturalWidth && naturalHeight) {
    naturalAspectRatio.value = naturalWidth / naturalHeight
  }

  isLoaded.value = true
  emit('load', props.src)
}

function handleError() {
  isFailed.value = true
  emit('error', props.src)
}

// An SSR image has already loaded or failed before hydration, so its load and error events are
// gone. Read the result from the element once mounted.
onMounted(() => {
  const img = imgRef.value

  if (!img?.complete) {
    return
  }

  if (img.naturalWidth > 0) {
    handleLoad()
  } else {
    handleError()
  }
})

watch(
  () => props.src,
  () => {
    isLoaded.value = false
    isFailed.value = false
    naturalAspectRatio.value = undefined
  }
)
</script>
