import { execFileSync } from 'node:child_process'
import { readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const srcDir = new URL('../src/', import.meta.url)
const repoRoot = fileURLToPath(new URL('../../../', import.meta.url))
const header = '// Generated by scripts/generateIcons.mjs. Do not edit.\n'

const names = readdirSync(new URL('svg/', srcDir))
  .filter(file => file.endsWith('.svg'))
  .map(file => file.slice(0, -'.svg'.length))
  .sort((a, b) => a.localeCompare(b))

if (names.length === 0) {
  throw new Error('No SVG files found in src/svg')
}

const iconNamesSource = `${header}export type IconName =\n${names.map(name => `  | '${name}'`).join('\n')}\n`

// The reference lets packages that type-check icons from src/ (via hakka-source) see the *.svg declaration.
// svg.d.ts only holds an ambient module declaration, so it cannot be pulled in with an import.
const iconMapSource = `${header}// eslint-disable-next-line @typescript-eslint/triple-slash-reference
/// <reference path="./svg.d.ts" />
import { defineAsyncComponent, type Component } from 'vue'

import type { IconName } from './iconNames'

export const iconMap: Record<IconName, Component> = {
${names.map(name => `  '${name}': defineAsyncComponent(() => import('./svg/${name}.svg')),`).join('\n')}
}
`

writeFileSync(new URL('iconNames.ts', srcDir), iconNamesSource)
writeFileSync(new URL('iconMap.ts', srcDir), iconMapSource)

// The generated layout does not match oxfmt; format here so format:check stays green.
// A failure must stop the script instead of leaving an unformatted file behind.
execFileSync('pnpm', ['exec', 'oxfmt', '--write', 'packages/icons/src/iconNames.ts', 'packages/icons/src/iconMap.ts'], {
  cwd: repoRoot,
  stdio: 'inherit',
})
